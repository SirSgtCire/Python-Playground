# Provide input for value x
x = int(input("Please give me x: "))
# Return the remainder of a number divided by 2, either 1 or 0
a = x % 2
# Booleanize the prior result, either True or False
b = bool(a)
print(b)
# Inverse the value of b
c = not b
# See if the string value of C matches 'True', then print result
d = str(c) in 'True'
print(d)